"""
أمثلة عملية على نظام GFC — State Machine لقوة الإشارة

مستويات الدخول:
  🟢🟢🟢 STRONG  — كسر الجد    (الأقوى)
  🟠🟠⬜ MEDIUM  — كسر الابن   (متوسط)
  🟡⬜⬜ WEAK    — كسر الحفيد  (سكالب)
  ⚪⚪⚪ NONE    — انتظار
"""

from gfc_bot import GFCBot

bot = GFCBot()

# بيانات الجد الهابط (آخر قمة منخفضة = 7.5 → مستوى كسر الجد)
GRAND_HIGHS = [11.0, 9.5, 8.0, 7.5]
GRAND_LOWS  = [10.0, 8.5, 6.5, 4.0]

# بيانات الابن الصاعد (أعلى نقطة = 6.55 → مستوى كسر الابن)
PARENT_HIGHS = [4.5, 5.2, 6.0, 6.55]
PARENT_LOWS  = [4.0, 4.4, 5.0, 5.8]

print("\n" + "▓"*56)
print("  State Machine — الجد–الابن–الحفيد")
print("  مستويات قوة الإشارة الثلاثة")
print("▓"*56)

# ══════════════════════════════════════════════════
#  ⚪ NONE — لا إشارة (انتظار)
#  السعر داخل النطاق، لا كسر في أي مستوى
# ══════════════════════════════════════════════════
bot.report_manual(
    "⚪ NONE — الوضع الحالي (لا إشارة)",
    grand_highs=GRAND_HIGHS, grand_lows=GRAND_LOWS,
    parent_highs=PARENT_HIGHS, parent_lows=PARENT_LOWS,
    child_highs=[6.55, 6.45, 6.33],
    child_lows =[6.40, 6.28, 6.16],
    current_price=6.18,
)

# ══════════════════════════════════════════════════
#  🟡 WEAK — كسر الحفيد (سكالب)
#  حفيد يكسر مقاومته الصغيرة لكن ابن وجد لم يتغيرا
# ══════════════════════════════════════════════════
bot.report_manual(
    "🟡 WEAK — كسر الحفيد (سكالب سريع)",
    grand_highs=GRAND_HIGHS, grand_lows=GRAND_LOWS,
    parent_highs=PARENT_HIGHS, parent_lows=PARENT_LOWS,
    child_highs=[6.16, 6.25, 6.35],   # حفيد بدأ يصعد، آخر قمة = 6.35
    child_lows =[6.10, 6.18, 6.25],
    current_price=6.38,                # فوق 6.35 بهامش ← كسر الحفيد ✅
)

# ══════════════════════════════════════════════════
#  🟠 MEDIUM — كسر الابن (إشارة متوسطة)
#  السعر تجاوز 6.55 (أعلى نقطة للابن)
#  الجد لا يزال هابطاً لكن الابن كُسر
# ══════════════════════════════════════════════════
bot.report_manual(
    "🟠 MEDIUM — كسر الابن فوق 6.55",
    grand_highs=GRAND_HIGHS, grand_lows=GRAND_LOWS,
    parent_highs=PARENT_HIGHS, parent_lows=PARENT_LOWS,
    child_highs=[6.55, 6.65, 6.75],   # حفيد صاعد مع الكسر
    child_lows =[6.45, 6.58, 6.68],
    current_price=6.78,               # فوق 6.55 ✅
)

# ══════════════════════════════════════════════════
#  🟢 STRONG — كسر الجد (الإشارة الكبرى)
#  السعر تجاوز 7.5 (آخر قمة منخفضة للجد)
#  هذه هي اللحظة التي ينتظرها المتداول الصبور
# ══════════════════════════════════════════════════
bot.report_manual(
    "🟢 STRONG — كسر الجد فوق 7.5 (الدخول الكبير)",
    grand_highs=[11.0, 9.5, 8.0, 7.5],
    grand_lows =[10.0, 8.5, 6.5, 4.0],
    parent_highs=[6.55, 7.0, 7.5, 7.8],
    parent_lows =[6.2,  6.5, 7.0, 7.3],
    child_highs=[7.50, 7.62, 7.78],
    child_lows =[7.42, 7.55, 7.68],
    current_price=7.76,              # فوق 7.5 ✅ كسر الجد
)

# ══════════════════════════════════════════════════
#  تطبيق مقارنة: BTC جد صاعد
#  يظهر كيف تختلف قوة الإشارة في سوق صاعد أصلاً
# ══════════════════════════════════════════════════
bot.report_manual(
    "🟢 BTC — جد صاعد + حفيد من دعم (STRONG في سياق صاعد)",
    grand_highs=[40000, 55000, 70000, 95000],
    grand_lows =[38000, 48000, 62000, 85000],
    parent_highs=[95000, 92000, 90000],
    parent_lows =[90000, 88000, 86000],
    child_highs=[86200, 87500, 89100],
    child_lows =[85800, 86500, 88100],
    current_price=89200,             # كسر آخر قمة الحفيد 89100
)

# ══════════════════════════════════════════════════
#  ملخص جدول قوة الإشارة
# ══════════════════════════════════════════════════
print("═"*56)
print("  جدول مرجعي: قوة الإشارة والمستوى المطلوب")
print("═"*56)
rows = [
    ("🟢🟢🟢 STRONG",  "كسر الجد",    "أعلى قمة منخفضة في الجد",   "الكبير"),
    ("🟠🟠⬜ MEDIUM",  "كسر الابن",   "أعلى نقطة للابن (6.55)",    "متوسط"),
    ("🟡⬜⬜ WEAK  ",  "كسر الحفيد",  "آخر قمة في الحفيد",          "سكالب"),
    ("⚪⚪⚪ NONE  ",  "لا كسر",      "─",                           "انتظار"),
]
print(f"  {'القوة':<20} {'الكسر':<14} {'المستوى':<26} {'الدخول'}")
print(f"  {'─'*52}")
for r in rows:
    print(f"  {r[0]:<20} {r[1]:<14} {r[2]:<26} {r[3]}")
print("═"*56 + "\n")
