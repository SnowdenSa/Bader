"""
أمثلة عملية على نظام GFC — الجد–الابن–الحفيد

القاعدة الذهبية (من المحاضرة):
  ❌ لا شراء في سوق هابط حتى يكسر الجد
  📌 حتى كسر الابن جيد — إشارة دخول مبكرة
  🔑 كسر الجد = دخول الكبير

المثال الحقيقي:
  الجد  هابط : من 11 (مقاومة) إلى 4 (دعم)، آخر قمة منخفضة = 7.5
  الابن صاعد : من 4 إلى 6.55 (مقاومة الابن)
  الحفيد هابط: آخر أسبوعين 6.33 → 6.16
"""

from gfc_bot import GFCBot

bot = GFCBot()

# ── بيانات الجد الهابط ──
# آخر قمة منخفضة للجد = 7.5  (مستوى الكسر الكبير)
GRAND_HIGHS = [11.0, 9.5, 8.0, 7.5]
GRAND_LOWS  = [10.0, 8.5, 6.5, 4.0]

# ── بيانات الابن الصاعد ──
# آخر قمة للابن = 6.55  (كسرها = إشارة جيدة)
PARENT_HIGHS = [4.5, 5.2, 6.0, 6.55]
PARENT_LOWS  = [4.0, 4.4, 5.0, 5.8]

print("\n" + "▓"*56)
print("  نظام GFC — سيناريوهات الجد–الابن–الحفيد")
print("▓"*56)

# ══════════════════════════════════════════════════
#  1. الوضع الحالي
#     جد هابط (آخر قمة 7.5) — لم يُكسر
#     ابن صاعد (آخر قمة 6.55) — لم يُكسر
#     حفيد هابط عند دعم 6.16
# ══════════════════════════════════════════════════
bot.report_manual(
    "① الوضع الحالي — جد وابن لم يُكسرا بعد",
    grand_highs=GRAND_HIGHS, grand_lows=GRAND_LOWS,
    parent_highs=PARENT_HIGHS, parent_lows=PARENT_LOWS,
    child_highs=[6.55, 6.45, 6.33],
    child_lows =[6.40, 6.28, 6.16],
    current_price=6.18,
)

# ══════════════════════════════════════════════════
#  2. كسر الابن (فوق 6.55)
#     الجد لا يزال هابطاً (7.5 لم يُكسر)
#     → إشارة جيدة لكن ليست الكبرى
# ══════════════════════════════════════════════════
bot.report_manual(
    "② كسر الابن فوق 6.55 ← إشارة جيدة",
    grand_highs=GRAND_HIGHS, grand_lows=GRAND_LOWS,
    parent_highs=PARENT_HIGHS, parent_lows=PARENT_LOWS,
    child_highs=[6.55, 6.68, 6.80],
    child_lows =[6.40, 6.55, 6.65],
    current_price=6.78,
)

# ══════════════════════════════════════════════════
#  3. كسر الجد (فوق 7.5)
#     هذه اللحظة الكبرى — الجد انكسر للأعلى
#     → أقوى إشارة شراء
# ══════════════════════════════════════════════════
bot.report_manual(
    "③ 🔑 كسر الجد فوق 7.5 ← الدخول الكبير",
    grand_highs=[11.0, 9.5, 8.0, 7.5],
    grand_lows =[10.0, 8.5, 6.5, 6.8],   # قاع الجد بدأ يرتفع
    parent_highs=[6.55, 7.0, 7.5, 7.8],
    parent_lows =[6.2,  6.5, 7.0, 7.3],
    child_highs=[7.5, 7.6, 7.8],
    child_lows =[7.3, 7.45, 7.6],
    current_price=7.75,
)

# ══════════════════════════════════════════════════
#  4. كسر دعم 6.16 للأسفل
#     الجد يستمر في هبوطه
#     → بيع / لا شراء
# ══════════════════════════════════════════════════
bot.report_manual(
    "④ كسر دعم 6.16 للأسفل — هبوط يستمر",
    grand_highs=GRAND_HIGHS, grand_lows=GRAND_LOWS,
    parent_highs=PARENT_HIGHS, parent_lows=PARENT_LOWS,
    child_highs=[6.33, 6.20, 6.10],
    child_lows =[6.18, 6.05, 5.88],
    current_price=5.92,
)

# ══════════════════════════════════════════════════
#  5. BTC — جد صاعد + تصحيح الابن + حفيد↑ من دعم
#     للمقارنة: كيف يختلف القرار في سوق صاعد
# ══════════════════════════════════════════════════
bot.report_manual(
    "⑤ BTC — جد↑، ابن في تصحيح، حفيد↑ من دعم",
    grand_highs=[40000, 55000, 70000, 95000],
    grand_lows =[38000, 48000, 62000, 85000],
    parent_highs=[95000, 92000, 90000],
    parent_lows =[90000, 88000, 86000],
    child_highs=[86200, 87500, 89000],
    child_lows =[85800, 86500, 88000],
    current_price=88500,
)
