import streamlit as st


def render():
    st.title("🚀 قانون نعم أولاً — اقتناص الفرصة قبل المنافس")
    st.caption("الفرص لا تنتظر. التاجر الناجح يقول نعم أولاً ويحل المشاكل لاحقاً.")
    st.markdown("---")

    st.markdown("""
    <div class="info-box">
    <b>مبدأ نعم أولاً:</b> المنافسة الحقيقية في السوق ليست في الجودة ولا في السعر —
    هي في <b>السرعة</b>. الزبون الذي يسأل 3 تجار، يشتري من أول واحد يقول "متوفر".
    التاجر الذي يفكر ويتردد ويقول "سأرد عليك لاحقاً" — خسر الصفقة قبل أن يبدأ.
    </div>
    """, unsafe_allow_html=True)

    st.subheader("🎯 محاكاة قرار الفرصة")
    st.markdown("اكتب تفاصيل الفرصة أو الطلب الذي أمامك الآن:")

    opportunity = st.text_area(
        "ما هي الفرصة أو الطلب؟",
        placeholder="مثال: عميل يريد طلبية 500 قطعة بشكل عاجل، لكن ليس عندي المخزون الكامل...",
        height=100,
    )

    st.markdown("---")
    st.subheader("✅ مصفوفة قرار نعم أولاً (5 أسئلة حاسمة)")

    col1, col2 = st.columns(2)
    with col1:
        q1 = st.radio(
            "1️⃣ هل يمكنك توفير المنتج أو الخدمة خلال 48 ساعة؟",
            ["نعم — أقدر أوفر بسرعة", "ربما — محتاج أتحقق من موردي", "لا — مستحيل بهذا الوقت"],
            key="q1",
        )
        q2 = st.radio(
            "2️⃣ هل هامش الربح في هذه الصفقة معقول (>15%)؟",
            ["نعم — الهامش جيد", "غير واضح — ما حسبت بعد", "لا — الهامش ضعيف أو سالب"],
            key="q2",
        )
        q3 = st.radio(
            "3️⃣ هل العميل موثوق وقادر على الدفع؟",
            ["نعم — عميل معروف أو دفع مقدم", "غير متأكد — عميل جديد", "لا — عميل مشكوك فيه"],
            key="q3",
        )
    with col2:
        q4 = st.radio(
            "4️⃣ هل قبول هذه الصفقة لا يضر بالتزاماتك الحالية؟",
            ["نعم — ما في تعارض", "ربما — محتاج أعيد ترتيب", "لا — سيؤثر على عملاء آخرين"],
            key="q4",
        )
        q5 = st.radio(
            "5️⃣ هل يمكنك الحصول على ما تحتاجه (مورد بديل، شراكة) إذا نقص مخزونك؟",
            ["نعم — عندي بدائل جاهزة", "ربما — أقدر أجد في وقت قصير", "لا — مصدر واحد فقط"],
            key="q5",
        )

    yes_count = sum([
        1 if "نعم" in q1 else (0.5 if "ربما" in q1 or "غير" in q1 else 0),
        1 if "نعم" in q2 else (0.5 if "غير" in q2 or "ربما" in q2 else 0),
        1 if "نعم" in q3 else (0.5 if "غير" in q3 else 0),
        1 if "نعم" in q4 else (0.5 if "ربما" in q4 else 0),
        1 if "نعم" in q5 else (0.5 if "ربما" in q5 else 0),
    ])

    st.markdown("---")
    st.subheader("📊 نتيجة مصفوفة القرار")
    st.metric("نقاط نعم أولاً", f"{yes_count:.1f} / 5")

    if yes_count >= 4:
        st.markdown("""
        <div class="success-box">
        🟢 <b>قل نعم الآن — الفرصة واضحة وآمنة!</b><br>
        جميع المؤشرات خضراء. لا تتردد — اتصل بالعميل الآن وأكد الطلب.
        المشاكل الصغيرة ستُحل في الطريق، أهم شيء أنك في الملعب.
        </div>
        """, unsafe_allow_html=True)
    elif yes_count >= 2.5:
        st.markdown("""
        <div class="warning-box">
        ⚠️ <b>قل نعم مع وضع شرط واحد:</b><br>
        الفرصة جيدة لكن فيها نقاط ضبابية. قل للعميل "نعم" لكن اجعل تأكيدها مشروطاً بـ:
        تأكيد الدفع المقدم، أو مهلة 24 ساعة للتأكد من المخزون.
        لا تقل "سأرد لاحقاً" — هذا يعني خسارة الصفقة.
        </div>
        """, unsafe_allow_html=True)
    else:
        st.markdown("""
        <div class="danger-box">
        🛑 <b>لا — هذه الصفقة خطرة:</b><br>
        المخاطر أكثر من الفرص. القبول المتسرع قد يضرك أكثر مما ينفعك.
        لكن لا تخسر العميل — قل له: "سأوفر لك في [تاريخ محدد]" وابحث عن الحل بهدوء.
        </div>
        """, unsafe_allow_html=True)

    st.markdown("---")
    st.subheader("⚡ 5 مواقف تطبيق قانون نعم أولاً")

    scenarios = [
        {
            "الموقف": "🛒 عميل يطلب منتجاً غير موجود في مخزونك",
            "الخطأ الشائع": "قول 'مو موجود' والانتهاء",
            "نعم أولاً": "قل 'متوفر خلال 24 ساعة' ثم اتصل بموردك فوراً أو اشترِ من منافسك وأعد البيع",
            "الدرس": "العميل اشترى من الشخص الأول الذي قال 'متوفر' — كن أنت ذاك الشخص",
        },
        {
            "الموقف": "🤝 طلبية كبيرة تفوق طاقتك الإنتاجية الحالية",
            "الخطأ الشائع": "الاعتذار عن الطلبية أو التردد",
            "نعم أولاً": "قل 'نعم' وابحث عن شريك أو مقاول فرعي يساعدك في التنفيذ",
            "الدرس": "الطلبية الكبيرة باب لتوسيع شبكتك وبناء علاقات توريد جديدة",
        },
        {
            "الموقف": "💬 عميل يريد تعديلاً غير معتاد على المنتج",
            "الخطأ الشائع": "الرفض لأن 'هذا مو طلبنا الأساسي'",
            "نعم أولاً": "قل 'نعم بسعر مختلف' — سعّر التعديل وحوّله لفرصة إضافية",
            "الدرس": "التخصيص يُضاعف هامش الربح ويبني ولاء العميل",
        },
        {
            "الموقف": "⏰ طلب عاجل في وقت غير مناسب",
            "الخطأ الشائع": "قول 'الدوام انتهى — تعال بكرة'",
            "نعم أولاً": "خدمة الطوارئ بسعر إضافي، أو توجيه العميل لمساعد موثوق",
            "الدرس": "العميل الذي خدمته في الوقت الصعب يصبح عميل مدى الحياة",
        },
        {
            "الموقف": "📦 طلب منتج بسعر أقل من سعرك",
            "الخطأ الشائع": "رفض الطلب لأن السعر لا يناسبك",
            "نعم أولاً": "قل 'هذا سعري' لكن قدّم قيمة مضافة تبرره — توصيل، ضمان، متابعة",
            "الدرس": "لا تخفض السعر — ارفع القيمة",
        },
    ]

    for s in scenarios:
        with st.expander(s["الموقف"]):
            col_a, col_b = st.columns(2)
            with col_a:
                st.markdown(f"""
                <div class="danger-box">
                ❌ <b>الخطأ الشائع:</b><br>{s["الخطأ الشائع"]}
                </div>
                """, unsafe_allow_html=True)
            with col_b:
                st.markdown(f"""
                <div class="success-box">
                ✅ <b>نعم أولاً:</b><br>{s["نعم أولاً"]}
                </div>
                """, unsafe_allow_html=True)
            st.markdown(f"💡 **الدرس:** {s['الدرس']}")

    st.markdown("---")
    st.subheader("📱 أداة تتبع الفرص المُقتنصة")
    st.markdown("سجّل الفرص التي قلت لها نعم هذا الشهر لقياس أثر القانون:")

    col_m1, col_m2, col_m3 = st.columns(3)
    with col_m1:
        yes_count_month = st.number_input("فرص قلت لها نعم ونجحت:", min_value=0, value=0)
    with col_m2:
        yes_failed = st.number_input("فرص قلت لها نعم ولم تكتمل:", min_value=0, value=0)
    with col_m3:
        missed = st.number_input("فرص ترددت فيها وضاعت:", min_value=0, value=0)

    total_opps = yes_count_month + yes_failed + missed
    if total_opps > 0:
        capture_rate = (yes_count_month / total_opps) * 100
        st.metric("معدل اقتناص الفرص", f"{capture_rate:.0f}%")
        if capture_rate >= 70:
            st.success("🟢 معدل اقتناص ممتاز — أنت تطبق قانون نعم أولاً بفاعلية عالية")
        elif capture_rate >= 40:
            st.warning("⚠️ هناك فرص ضائعة يمكن اقتناصها — راجع حالات التردد")
        else:
            st.error("🛑 معدل اقتناص منخفض — تحتاج تطبيقاً أقوى لمبدأ نعم أولاً")

    st.markdown("---")
    st.markdown("""
    <div class="success-box">
    🚀 <b>القاعدة الذهبية النهائية:</b><br>
    قل نعم، ثم اكتشف كيف تُنفّذها — ليس العكس.<br>
    التاجر الذي ينتظر حتى يكون مستعداً 100% لا يبدأ أبداً.
    الأسواق تكافئ الجريء والسريع، لا المثالي البطيء.
    </div>
    """, unsafe_allow_html=True)
